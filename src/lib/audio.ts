/** Voice profiles generated by scripts/generate-voices.mjs. */
export type VoiceProfile = 'f' | 'm' | 'kid' | 'elder-f' | 'elder-m'

const WHO_PROFILE: Record<string, VoiceProfile> = {
  wife: 'f',
  son: 'kid',
  daughter: 'kid',
  mil: 'elder-f',
  grandma: 'elder-f',
  fil: 'elder-m',
  friend: 'm',
  waiter: 'm',
  seller: 'f',
  neighbour: 'f',
}

/** The voice for a conversation line: "me" follows how the learner is addressed. */
export const voiceForWho = (who: string, speaker: 'm' | 'f'): VoiceProfile => (who === 'me' ? speaker : (WHO_PROFILE[who] ?? 'f'))

const VOICES_BASE = `${import.meta.env.BASE_URL}voices/`
let clips = new Map<string, string>()
let clipSource: { provider: string | null; voices: Partial<Record<VoiceProfile, string>> } = { provider: null, voices: {} }
let manifestPromise: Promise<void> | null = null

/** Loads public/voices/manifest.json once. Missing or broken manifests simply mean "no clips". */
export function manifestReady(): Promise<void> {
  if (!manifestPromise)
    manifestPromise = fetch(`${VOICES_BASE}manifest.json`, { cache: 'no-cache' })
      .then((r) => (r.ok ? r.json() : null))
      .then((m: { clips?: Record<string, string>; provider?: string; voices?: Partial<Record<VoiceProfile, string>> } | null) => {
        if (m?.clips) clips = new Map(Object.entries(m.clips))
        // Older manifests (Azure only) have no provider field.
        if (m) clipSource = { provider: m.provider ?? (m.clips ? 'azure' : null), voices: m.voices ?? {} }
      })
      .catch(() => undefined)
  return manifestPromise
}

/** Who voiced the clips: provider ("elevenlabs" | "azure") and the voice name per profile. */
export const clipVoices = () => clipSource

/** A label for the main voice, e.g. "Milena (ElevenLabs)" or "Kalina (Microsoft)"; null without clips. */
export function clipVoiceLabel(): string | null {
  if (!clips.size || !clipSource.provider) return null
  const provider = clipSource.provider === 'elevenlabs' ? 'ElevenLabs' : clipSource.provider === 'azure' ? 'Microsoft' : clipSource.provider
  const name = clipSource.voices.f ?? (clipSource.provider === 'azure' ? 'Kalina' : null)
  return name ? `${name} (${provider})` : provider
}
if (typeof window !== 'undefined') void manifestReady()

/** True when a Microsoft voice clip exists for this text and profile. */
export const hasClip = (text: string, voice: VoiceProfile = 'f') => clips.has(`${voice}|${text.trim()}`)
/** Number of clips available (0 until the manifest loads, or when there are none). */
export const clipCount = () => clips.size
/** URLs of every clip, for saving them all for offline use. */
export const clipUrls = () => [...new Set(clips.values())].map((k) => `${VOICES_BASE}${k}.mp3`)
const clipUrl = (text: string, voice: VoiceProfile) => {
  const k = clips.get(`${voice}|${text.trim()}`)
  return k ? `${VOICES_BASE}${k}.mp3` : null
}

// Clips are fetched (through the service worker cache) and played from blob URLs, which avoids
// iOS media range requests against cached responses.
const blobUrls = new Map<string, string>()
async function clipBlobUrl(url: string): Promise<string | null> {
  const hit = blobUrls.get(url)
  if (hit) return hit
  try {
    const res = await fetch(url)
    if (!res.ok) return null
    const obj = URL.createObjectURL(await res.blob())
    blobUrls.set(url, obj)
    if (blobUrls.size > 80) {
      const [first, firstObj] = blobUrls.entries().next().value as [string, string]
      URL.revokeObjectURL(firstObj)
      blobUrls.delete(first)
    }
    return obj
  } catch {
    return null
  }
}

// One shared audio element: once it has played inside a tap, iOS lets it play again later.
let player: HTMLAudioElement | null = null
type PlayResult = 'done' | 'failed' | 'interrupted'
let settle: ((r: PlayResult) => void) | null = null
const getPlayer = () => {
  if (!player) {
    player = new Audio()
    player.preload = 'auto'
    ;(player as HTMLAudioElement & { playsInline?: boolean }).playsInline = true
  }
  return player
}

/** Plays a URL on the shared element: done, failed (try something else) or interrupted (stop quietly). */
function playUrl(url: string, slow?: boolean): Promise<PlayResult> {
  const a = getPlayer()
  settle?.('interrupted')
  return new Promise<PlayResult>((resolve) => {
    let done = false
    const finish = (r: PlayResult) => {
      if (done) return
      done = true
      clearTimeout(guard)
      a.onended = a.onerror = null
      if (settle === finish) settle = null
      resolve(r)
    }
    settle = finish
    const guard = setTimeout(() => finish('done'), 20_000)
    a.onended = () => finish('done')
    a.onerror = () => finish('failed')
    a.src = url
    a.preservesPitch = true
    a.defaultPlaybackRate = a.playbackRate = slow ? 0.75 : 1
    a.play().catch((e: DOMException) => finish(e?.name === 'AbortError' ? 'interrupted' : 'failed'))
  })
}

/**
 * Say something in Bulgarian. Order: her recording for this item, then the Microsoft voice clip,
 * then the phone's own Bulgarian voice.
 */
export async function speak(text: string, opts: { slow?: boolean; itemId?: string; voice?: VoiceProfile } = {}): Promise<void> {
  // WebKit can drop an utterance queued in the same tick as cancel(); give it a beat.
  if (halt()) await new Promise((r) => setTimeout(r, 60))
  if (opts.itemId) {
    const rec = await db.recordings.get(opts.itemId).catch(() => undefined)
    if (rec) {
      let url = urlCache.get(opts.itemId)
      if (!url) {
        url = URL.createObjectURL(rec.blob)
        urlCache.set(opts.itemId, url)
      }
      if ((await playUrl(url, opts.slow)) !== 'failed') return
    }
  }
  await manifestReady()
  const clip = clipUrl(text, opts.voice ?? 'f') ?? (opts.voice && opts.voice !== 'f' ? clipUrl(text, 'f') : null)
  if (clip) {
    const asked = ++speakSeq
    const obj = await clipBlobUrl(clip)
    // A newer speak() started while this clip was loading: let that one talk.
    if (asked !== speakSeq) return
    if (obj && (await playUrl(obj, opts.slow)) !== 'failed') return
  }
  if (typeof speechSynthesis === 'undefined') return
  return new Promise((resolve) => {
    const u = new SpeechSynthesisUtterance(text)
    u.lang = 'bg-BG'
    if (voice) u.voice = voice
    u.rate = opts.slow ? 0.55 : 0.9
    u.onend = () => resolve()
    u.onerror = () => resolve()
    speechSynthesis.speak(u)
    // iOS sometimes never fires onend; don't hang the UI.
    setTimeout(resolve, 600 + text.length * (opts.slow ? 160 : 90))
  })
}

const urlCache = new Map<string, string>()
let speakSeq = 0

/** Stops whatever is playing. */
export function stopSpeaking() {
  halt()
}

/** Stops playback; returns true if speech had to be cancelled. */
function halt(): boolean {
  let cancelled = false
  if (typeof speechSynthesis !== 'undefined' && (speechSynthesis.speaking || speechSynthesis.pending)) {
    speechSynthesis.cancel()
    cancelled = true
  }
  if (player && !player.paused) player.pause()
  // Let anyone awaiting the interrupted clip carry on.
  speakSeq++
  settle?.('interrupted')
  return cancelled
}

let unlocked = false

/** A tiny silent WAV, built once, used to unlock the shared audio element inside a tap. */
const SILENT_WAV = (() => {
  const samples = 800
  const buf = new Uint8Array(44 + samples * 2)
  const v = new DataView(buf.buffer)
  const str = (o: number, t: string) => [...t].forEach((c, i) => v.setUint8(o + i, c.charCodeAt(0)))
  str(0, 'RIFF')
  v.setUint32(4, 36 + samples * 2, true)
  str(8, 'WAVEfmt ')
  v.setUint32(16, 16, true)
  v.setUint16(20, 1, true)
  v.setUint16(22, 1, true)
  v.setUint32(24, 8000, true)
  v.setUint32(28, 16000, true)
  v.setUint16(32, 2, true)
  v.setUint16(34, 16, true)
  str(36, 'data')
  v.setUint32(40, samples * 2, true)
  let bin = ''
  buf.forEach((b) => (bin += String.fromCharCode(b)))
  return `data:audio/wav;base64,${btoa(bin)}`
})()
/**
 * iOS only lets a page speak or play sound after something was started inside a tap.
 * Call this synchronously from a tap handler (it is also wired to the first touch).
 */
export function unlockAudio() {
  if (unlocked) return
  unlocked = true
  try {
    if (typeof speechSynthesis !== 'undefined') {
      const u = new SpeechSynthesisUtterance(' ')
      u.volume = 0
      u.lang = 'bg-BG'
      speechSynthesis.speak(u)
    }
  } catch {
    /* no speech on this device */
  }
  try {
    const a = getPlayer()
    a.src = SILENT_WAV
    a.play().catch(() => undefined)
  } catch {
    /* no media element */
  }
  try {
    const c = ac()
    // A silent one-sample buffer fully unlocks WebAudio on older iOS.
    const buf = c.createBuffer(1, 1, 22050)
    const src = c.createBufferSource()
    src.buffer = buf
    src.connect(c.destination)
    src.start(0)
    warmSfx()
  } catch {
    /* no WebAudio */
  }
}

