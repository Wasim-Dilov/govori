// ------------------------------------------------------------- text to speech
let voice: SpeechSynthesisVoice | null = null
let voicesLoaded = false

function pickVoice() {
  if (typeof speechSynthesis === 'undefined') return
  const voices = speechSynthesis.getVoices()
  if (!voices.length) return
  voicesLoaded = true
  const bg = voices.filter((v) => v.lang?.toLowerCase().replace('_', '-').startsWith('bg'))
  // Prefer enhanced/premium voices when the phone has them downloaded.
  voice = bg.find((v) => /enhanced|premium|neural/i.test(v.name)) ?? bg[0] ?? null
}
if (typeof speechSynthesis !== 'undefined') {
  pickVoice()
  speechSynthesis.addEventListener?.('voiceschanged', pickVoice)
}

/** True if a Bulgarian voice is installed on this device. Null while unknown. */
export function hasBulgarianVoice(): boolean | null {
  if (typeof speechSynthesis === 'undefined') return false
  if (!voicesLoaded) pickVoice()
  return voicesLoaded ? !!voice : null
}

let statusPromise: Promise<boolean> | null = null

/**
 * Whether this device can speak Bulgarian. Waits briefly for the voice list,
 * which some browsers fill in asynchronously. No voices at all counts as no.
 */
export function bulgarianVoiceStatus(timeoutMs = 1500): Promise<boolean> {
  if (typeof speechSynthesis === 'undefined') return Promise.resolve(false)
  pickVoice()
  if (voicesLoaded) return Promise.resolve(!!voice)
  if (!statusPromise)
    statusPromise = new Promise<boolean>((resolve) => {
      const done = () => {
        pickVoice()
        if (!voicesLoaded) return false
        clearInterval(poll)
        clearTimeout(timer)
        speechSynthesis.removeEventListener?.('voiceschanged', onChange)
        resolve(!!voice)
        return true
      }
      const onChange = () => void done()
      speechSynthesis.addEventListener?.('voiceschanged', onChange)
      // Safari fills the list without always firing voiceschanged.
      const poll = setInterval(done, 150)
      const timer = setTimeout(() => {
        clearInterval(poll)
        speechSynthesis.removeEventListener?.('voiceschanged', onChange)
        statusPromise = null
        resolve(false)
      }, timeoutMs)
    })
  return statusPromise
}

